interface LanguageContextValue {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>("id");

  useEffect(() => {
    const saved = window.localStorage.getItem("elektronikmart-language");
    if (saved === "id" || saved === "en") setLanguageState(saved);
  }, []);

  useEffect(() => {
    window.localStorage.setItem("elektronikmart-language", language);
    document.documentElement.lang = language;
  }, [language]);

  function setLanguage(nextLanguage: Language) {
    setLanguageState(nextLanguage);
  }

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        t: (key, vars) => {
          let text = dictionaries[language][key] ?? dictionaries.id[key] ?? key;
          if (vars) {
            for (const [name, value] of Object.entries(vars)) {
              text = text.replaceAll(`{${name}}`, String(value));
            }
          }
          return text;
        },
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage harus dipakai di dalam LanguageProvider");
  return context;
}

export type { Language };
